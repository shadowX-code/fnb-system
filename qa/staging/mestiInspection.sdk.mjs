import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
const root = process.env.FEEDX_MCP_SDK;
if (!root) throw new Error("Set FEEDX_MCP_SDK to a temporary official @modelcontextprotocol/sdk dist/esm directory.");
const { Client } = await import(pathToFileURL(`${root}/client/index.js`));
const { StreamableHTTPClientTransport } = await import(pathToFileURL(`${root}/client/streamableHttp.js`));
const credentials = JSON.parse(readFileSync(process.argv[2], "utf8"));
assert.equal(credentials.endpoint, "https://ujkzdaaadnvcfayuldmh.supabase.co/functions/v1/factory-mesti-mcp");
const client = new Client({ name: "feedx-independent-mcp-sdk-qa", version: "1.0.0" });
const transport = new StreamableHTTPClientTransport(new URL(credentials.endpoint), { requestInit: { headers: { Authorization: credentials.authorization } } });
await client.connect(transport);
const tools = await client.listTools();
assert.equal(tools.tools.length, 5);
const daily = await client.callTool({ name: "get_mesti_daily_status", arguments: {} });
assert.equal(daily.isError, false);
assert.equal(daily.structuredContent.coverage.length, 8);
await client.close();
console.log("PASS: official MCP SDK initialized, discovered exactly five tools and reviewed yesterday over authenticated Streamable HTTP.");
